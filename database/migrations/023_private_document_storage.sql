-- Private original-file storage for AI-RMMS documents.
-- Production rollout requires separate approval after staging/JWT tests.
-- Existing documents keep storage_path NULL and are not assigned fake paths.

ALTER TABLE public.documents
  ADD COLUMN IF NOT EXISTS storage_path text;

COMMENT ON COLUMN public.documents.storage_path IS
  'Private Supabase Storage object path; NULL means no original file is stored. Never store a public URL here.';

-- The bucket is private. This migration is intended for isolated integration
-- tests first; do not apply it to production without an approved rollout.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'documents-private',
  'documents-private',
  false,
  10485760,
  ARRAY[
    'text/plain',
    'text/csv',
    'application/pdf',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'application/vnd.ms-excel.sheet.macroEnabled.12'
  ]
)
ON CONFLICT (id) DO UPDATE
SET public = false,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

-- Object names are generated by the backend:
-- <organization_uuid>/<department_code>/<document_uuid>/<random_uuid>.<ext>
-- Policies match the complete object path against the document row; path
-- segments alone are not considered authorization.

DROP POLICY IF EXISTS documents_private_select_authorized ON storage.objects;
CREATE POLICY documents_private_select_authorized
ON storage.objects
FOR SELECT
TO authenticated
USING (
  bucket_id = 'documents-private'
  AND EXISTS (
    SELECT 1
    FROM public.documents d
    WHERE d.storage_path = storage.objects.name
      AND d.organization_id::text = split_part(storage.objects.name, '/', 1)
      AND d.department_code = split_part(storage.objects.name, '/', 2)
      AND d.id::text = split_part(storage.objects.name, '/', 3)
      AND (
        private.is_org_admin(d.organization_id)
        OR (
          d.department_code IS NOT NULL
          AND public.has_department_role(
            d.organization_id,
            d.department_code,
            ARRAY['department_manager', 'officer', 'read_only']::text[]
          )
        )
      )
  )
);

DROP POLICY IF EXISTS documents_private_insert_authorized ON storage.objects;
CREATE POLICY documents_private_insert_authorized
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
  bucket_id = 'documents-private'
  AND EXISTS (
    SELECT 1
    FROM public.documents d
    WHERE d.storage_path = storage.objects.name
      AND d.organization_id::text = split_part(storage.objects.name, '/', 1)
      AND d.department_code = split_part(storage.objects.name, '/', 2)
      AND d.id::text = split_part(storage.objects.name, '/', 3)
      AND (
        private.is_org_admin(d.organization_id)
        OR (
          d.department_code IS NOT NULL
          AND public.has_department_role(
            d.organization_id,
            d.department_code,
            ARRAY['department_manager', 'officer']::text[]
          )
        )
      )
  )
);

DROP POLICY IF EXISTS documents_private_delete_authorized ON storage.objects;
CREATE POLICY documents_private_delete_authorized
ON storage.objects
FOR DELETE
TO authenticated
USING (
  bucket_id = 'documents-private'
  AND EXISTS (
    SELECT 1
    FROM public.documents d
    WHERE d.storage_path = storage.objects.name
      AND d.organization_id::text = split_part(storage.objects.name, '/', 1)
      AND d.department_code = split_part(storage.objects.name, '/', 2)
      AND d.id::text = split_part(storage.objects.name, '/', 3)
      AND (
        private.is_org_admin(d.organization_id)
        OR (
          d.department_code IS NOT NULL
          AND public.has_department_role(
            d.organization_id,
            d.department_code,
            ARRAY['department_manager', 'officer']::text[]
          )
        )
      )
  )
);

